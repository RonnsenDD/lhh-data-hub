import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { Buffer } from "node:buffer";

const directory = new URL("./", import.meta.url);
const buildScript = new URL("./build-editor-bundle.mjs", import.meta.url);
const bundlePath = new URL("./worker.bundle.js", import.meta.url);

test("manual-editor bundle is current, self-contained, and preserves V2 endpoints", async () => {
  execFileSync(process.execPath, [buildScript.pathname, "--check"], { stdio: "pipe" });
  const source = await readFile(bundlePath, "utf8");
  assert.match(source, /^\/\/ Generated by build-editor-bundle\.mjs/m);
  assert.equal(/^import\s/m.test(source), false);
  assert.equal((source.match(/^export default\s/mg) ?? []).length, 1);

  const moduleUrl = "data:text/javascript;base64," + Buffer.from(source).toString("base64");
  const workerModule = await import(moduleUrl);
  assert.equal(typeof workerModule.default.fetch, "function");
  assert.equal(typeof workerModule.default.scheduled, "function");

  const calls = [];
  const logs = [];
  const originalFetch = globalThis.fetch;
  const originalLog = console.log;
  globalThis.fetch = async (input) => {
    const url = new URL(String(input));
    calls.push(url);
    assert.notEqual(url.origin, "https://api.github.com");
    return new Response(null, { status: 404 });
  };
  console.log = (line) => logs.push(String(line));
  try {
    const response = await workerModule.default.fetch(
      new Request("https://worker.example/status"),
      { GITHUB_APP_READ_ENABLED: "true" },
    );
    assert.equal(response.status, 200);
    const status = await response.json();
    assert.equal(status.sources.length, 7);
    assert.equal("workflows" in status, false);

    await workerModule.default.scheduled(
      { cron: "*/5 * * * *", scheduledTime: Date.now() },
      { GITHUB_APP_READ_ENABLED: "false" },
    );
  } finally {
    globalThis.fetch = originalFetch;
    console.log = originalLog;
  }
  assert.equal(calls.length, 14);
  assert.equal(calls.some((url) => url.origin === "https://api.github.com"), false);
  const feedLog = logs.map((line) => JSON.parse(line)).find((item) => item.event === "feed_watchdog_check");
  assert.equal(feedLog.sources.length, 7);
  assert.equal(logs.some((line) => JSON.parse(line).event === "github_workflow_observation"), false);
});
